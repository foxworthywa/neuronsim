// Writes ../anatomy.js: the anatomical figure as a data URI, so that the single-file build
// (dist/immune.html) carries it with no second file to host. Run after replacing the image:
//   node immune/img/embed.js
// The figure and its credit: see CREDITS.md in this folder.
'use strict';
const fs = require('fs'), path = require('path');
const file = path.join(__dirname, 'lymphatic-system-openstax.jpg');
const b64 = fs.readFileSync(file).toString('base64');
const out = `/* Generated by immune/img/embed.js from immune/img/lymphatic-system-openstax.jpg. Do not edit.
 * "Anatomy of the Lymphatic System" by OpenStax College, from Anatomy & Physiology (Connexions,
 * 2013), via Wikimedia Commons. Licensed CC BY 3.0 (not under this repository's licence).
 * Changed here: recompressed. See immune/img/CREDITS.md. */
window.IM_ANATOMY = {
  width: 1115, height: 1181,
  title: 'Anatomy of the Lymphatic System',
  credit: 'OpenStax College, Anatomy & Physiology (2013), via Wikimedia Commons. CC BY 3.0.',
  source: 'https://commons.wikimedia.org/wiki/File:2201_Anatomy_of_the_Lymphatic_System.jpg',
  license: 'https://creativecommons.org/licenses/by/3.0/',
  src: 'data:image/jpeg;base64,${b64}',
};
`;
fs.writeFileSync(path.join(__dirname, '..', 'anatomy.js'), out);
console.log('wrote immune/anatomy.js', (out.length / 1024).toFixed(0), 'KB');
